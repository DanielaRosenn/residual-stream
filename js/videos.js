/* Explainer videos: one "Watch" card per chapter that has an episode.
   Reads window.RS_VIDEOS from js/videos-data.js (generated by video/publish_media.py).
   The card starts collapsed (a lazy poster image and a button), so nothing is downloaded until the
   reader asks. The MP4 streams from the GitHub release; poster and subtitles are same-origin files in
   media/. Inserted before the chapter's first .panel; js/challenges.js runs later and puts its
   "guess first" card right before that panel, so the order is: intro text, video, guess, demo. */
(function () {
  const list = window.RS_VIDEOS || [];
  const base = window.RS_VIDEO_BASE || "";
  if (!list.length || !base) return;
  // media/ sits at the site root; this script is js/videos.js, so the root is one level up from it.
  const root = new URL("../", document.currentScript.src).href;

  function minutesLabel(seconds) {
    const halves = Math.max(1, Math.round(seconds / 30)); // nearest half minute
    const m = halves / 2;
    if (LANG === "he") {
      if (m === 1) return "דקה";
      if (m === 1.5) return "דקה וחצי";
      return `${m} דקות`;
    }
    const whole = Math.floor(m);
    return `${whole}${m % 1 ? "½" : ""} min`;
  }

  list.forEach((v) => {
    const sec = document.getElementById(v.section);
    if (!sec) return;
    const title = sec.dataset.title || "";
    const card = document.createElement("div");
    card.className = "vid-card";
    card.id = `vid-${v.section}`;

    const thumb = document.createElement("img");
    thumb.className = "vid-thumb";
    thumb.src = root + `media/${v.stem}.jpg`;
    thumb.alt = "";
    thumb.loading = "lazy";
    thumb.width = 960;
    thumb.height = 540;

    const text = document.createElement("div");
    text.className = "vid-text";
    const kick = document.createElement("p");
    kick.className = "vid-kick";
    kick.textContent = tr(`Watch first · ${minutesLabel(v.seconds)}`, `צפו קודם · ${minutesLabel(v.seconds)}`);
    const h = document.createElement("p");
    h.className = "vid-title";
    h.innerHTML = `<span dir="ltr">EP ${v.ep}</span> · ${title}`;
    const note = document.createElement("p");
    note.className = "vid-note";
    note.textContent = tr(
      "A short animated explainer: Vera the guide and Toki the token talk it through. Subtitles included.",
      "סרטון הסבר קצר ומונפש: ורה המדריכה וטוקי הטוקן מסבירים את הנושא. הסרטון באנגלית, עם כתוביות באנגלית."
    );
    const btn = document.createElement("button");
    btn.type = "button";
    btn.className = "btn vid-play";
    btn.textContent = tr("Play video", "הפעלת הסרטון");
    text.append(kick, h, note, btn);
    card.append(thumb, text);

    function open() {
      const video = document.createElement("video");
      video.className = "vid-player";
      video.controls = true;
      video.preload = "metadata";
      video.playsInline = true;
      video.poster = thumb.src;
      video.setAttribute("aria-label", `EP ${v.ep} · ${title}`);
      const src = document.createElement("source");
      src.src = base + `${v.stem}.mp4`;
      src.type = "video/mp4";
      const track = document.createElement("track");
      track.kind = "subtitles";
      track.srclang = "en";
      track.label = "English";
      track.src = root + `media/${v.stem}.vtt`;
      video.append(src, track);
      card.classList.add("is-open");
      card.replaceChildren(video);
      const p = video.play();
      if (p && p.catch) p.catch((err) => console.info("video autoplay after click was refused:", err.name));
    }
    btn.addEventListener("click", open);
    thumb.addEventListener("click", open);

    const firstPanel = sec.querySelector(".panel");
    if (firstPanel) firstPanel.before(card);
    else sec.append(card);
  });
})();
